"""Distribution integrity checks for the exact approved sprite sheet.

These verify the distributable geometry and bytes, not artistic quality or
semantic direction review. Existing artwork is not regenerated by these tests.
"""
from pathlib import Path
import hashlib
import json
import unittest

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]


class SpriteDistributionTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.manifest = json.loads((ROOT / "assets/manifest.json").read_text(encoding="utf-8"))
        cls.spec = cls.manifest["sprite"]
        cls.path = ROOT / "assets" / cls.spec["file"]
        with Image.open(cls.path) as image:
            image.load()
            cls.format = image.format
            cls.image = image.copy()

    def test_file_integrity_and_portable_resource_path(self):
        relative = Path(self.spec["file"])
        self.assertFalse(relative.is_absolute())
        self.assertEqual(relative.parts, ("xinglan-v2.png",))
        self.assertEqual(hashlib.sha256(self.path.read_bytes()).hexdigest(), self.spec["sha256"])
        self.assertEqual(self.path.stat().st_size, self.spec["bytes"])
        self.assertEqual(self.format, "PNG")
        self.assertEqual(self.image.mode, "RGBA")

    def test_v2_geometry_and_animation_timings(self):
        self.assertEqual(self.image.size, (1536, 2288))
        self.assertEqual((self.spec["cell_width"], self.spec["cell_height"]), (192, 208))
        self.assertEqual((self.spec["columns"], self.spec["rows"]), (8, 11))
        expected = [
            ("idle", 6), ("running-right", 8), ("running-left", 8),
            ("waving", 4), ("jumping", 5), ("failed", 8),
            ("waiting", 6), ("running", 6), ("review", 6),
        ]
        states = self.manifest["states"]
        self.assertEqual([(s["id"], s["frame_count"]) for s in states], expected)
        self.assertEqual([s["row"] for s in states], list(range(9)))
        for state in states:
            with self.subTest(state=state["id"]):
                self.assertEqual(len(state["durations_ms"]), state["frame_count"])
                self.assertTrue(all(type(t) is int and 40 <= t <= 2000 for t in state["durations_ms"]))

    def test_all_required_frames_present_and_unused_cells_transparent(self):
        counts = [s["frame_count"] for s in self.manifest["states"]] + [8, 8]
        used = unused = 0
        alpha = self.image.getchannel("A")
        for row, count in enumerate(counts):
            for column in range(8):
                cell = alpha.crop((column * 192, row * 208, (column + 1) * 192, (row + 1) * 208))
                with self.subTest(row=row, column=column):
                    if column < count:
                        self.assertIsNotNone(cell.getbbox(), "Required character frame is blank")
                        used += 1
                    else:
                        self.assertIsNone(cell.getbbox(), "Unused cell has visible pixels")
                        unused += 1
        self.assertEqual((used, unused), (73, 15))

    def test_direction_manifest_is_complete_and_clockwise(self):
        look = self.manifest["look_directions"]
        self.assertEqual(look["rows"], [9, 10])
        self.assertEqual(look["frame_count"], 16)
        self.assertEqual(look["angles_degrees"], [i * 22.5 for i in range(16)])
        self.assertEqual(look["order"], "clockwise-from-screen-up")
        self.assertEqual(look["cardinals"], {"0": "screen-up", "90": "screen-right", "180": "screen-down", "270": "screen-left"})


if __name__ == "__main__":
    unittest.main(verbosity=2)
